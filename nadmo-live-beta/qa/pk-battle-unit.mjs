import assert from 'node:assert/strict';
import {proposePK,publicPK,consentPK,supportPK,checkPKDeadline,finishPK} from '../pk-battle.mjs';
const ids=['abcdefgh','guest0001','guest0002','guest0003'];
const guests=ids.slice(1).map(id=>({id,ready:true}));
const now=1000000;
let pk=proposePK({id:'battle00001',hostId:ids[0],guests,mode:'2v2',minutes:5,now});
assert.equal(pk.status,'pending');
assert.deepEqual(pk.teams.A,[ids[0],ids[1]]);
assert.deepEqual(pk.teams.B,[ids[2],ids[3]]);
assert.equal(publicPK(pk).votes,undefined);
assert.throws(()=>consentPK(pk,'wrongid00',true,now+1));
for(const guest of guests)pk=consentPK(pk,guest.id,true,now+100);
assert.equal(pk.status,'active');
assert.equal(pk.endsAt,now+100+300000);
assert.throws(()=>supportPK(pk,'', 'A',now+200));
pk=supportPK(pk,'viewerid123','B',now+200);
assert.equal(pk.scores.B,1);
assert.throws(()=>supportPK(pk,'viewerid123','B',now+201));
pk=supportPK(pk,'viewerid123','A',now+15500);
assert.equal(pk.scores.A,1);
pk=checkPKDeadline(pk,pk.endsAt);
assert.equal(pk.status,'finished');
assert.equal(pk.winner,'draw');
assert.equal(publicPK(pk).votes,undefined);
assert.throws(()=>supportPK(pk,'viewerid123','A',pk.endsAt+1));
const one=proposePK({id:'battle00002',hostId:ids[0],guests,mode:'1v1',minutes:3,now});
assert.equal(consentPK(one,ids[1],false,now+1).reason,'invitation-declined');
assert.equal(checkPKDeadline(one,now+45000).reason,'invitation-timeout');
assert.throws(()=>proposePK({id:'battle00003',hostId:ids[0],guests:[],mode:'2v2',minutes:5,now}));
assert.equal(finishPK(null),null);
console.log('NADMO PK pure-state unit test PASS (no fictitious money)');
