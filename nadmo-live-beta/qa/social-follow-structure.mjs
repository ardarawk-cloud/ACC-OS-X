import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const html=readFileSync(new URL('../public/app/index.html',import.meta.url),'utf8');
for(const [tab,label] of [['socialPage','SOSIAL'],['messagesPage','PESAN']]){
 assert.ok(html.includes('data-tab="'+tab+'" aria-label="'+(label==='SOSIAL'?'Sosial':'Pesan')+'"'));
 if(tab==='messagesPage')assert.ok(html.includes('>PESAN<span id="messageUnreadBadge" class="message-nav-badge" hidden></span></button>'),'PESAN label and unread badge must remain intact');
 else assert.ok(html.includes('>'+label+'</button>'));
}
for(const id of ['meFollowers','meFollowing','meFollowersCount','meFollowingCount','socialConnectionsPage'])assert.ok(html.includes('id="'+id+'"'));
assert.ok(html.includes('transform:skew(-10deg)'));
assert.ok(html.includes('data-tab="studio" class="broadcast"'));
const accountPage=html.split('<section id="accountPage" class="hide">')[1]?.split('<section id="walletPage"')[0]||'';
const preferencesPage=html.split('<section id="preferencesPage" class="hide">')[1]?.split('<section id="accountPage"')[0]||'';
const socialPage=html.split('<section id="socialPage" class="hide">')[1]?.split('<section id="messagesPage"')[0]||'';
assert.ok(accountPage,'Account editor must exist');
assert.ok(socialPage,'Social page must exist');
assert.ok(!accountPage.includes('KELOLA POSTINGAN'),'ME edit must never include post manager');
assert.ok(!accountPage.includes('meNewPost'),'Legacy post-create button must not be in ME');
assert.ok(!preferencesPage.includes('data-open-page="draftsPage"'),'Draf management must not be in ME settings');
assert.ok(socialPage.includes('id="socialManageDrafts"'),'Drafts are accessed from SOSIAL');
assert.ok(html.includes("if(onPage==='draftsPage')show('socialPage');"));
assert.ok(html.includes("name==='draftsPage'?'socialPage'"));
assert.ok(!html.includes('profilePublishedPosts'),'Published post duplication must be eliminated');
// Repost is content-first: no avatar enlargement in ME, no duplicate heading.
assert.match(html,/#meRepostedFeed \.post-top img\{width:28px;height:28px/);
assert.match(html,/\.profile-post-card \.social-action-row\{display:grid;grid-template-columns:repeat\(4,minmax\(0,1fr\)\)/);
assert.ok(html.includes("const card=makePublicPost({...item.original,repostMe:true,repostId:item.id,repostCaption:item.caption||''});"));
assert.ok(html.includes("/api/account/social/unrepost"));
assert.ok(html.includes("if(item.originalId&&!item.repostMe)"));
assert.ok(html.includes("id=\"socialShareSheet\""));
assert.ok(html.includes("const stats=document.createElement('div');stats.className='social-stats'"));
assert.ok(html.includes("actions.append(like,comment,share);"));
assert.ok(html.includes("id=\"socialShareCaption\""));
assert.ok(html.includes("Selengkapnya"));
const studio=html.split('<section id="studio" class="hide">')[1]?.split('<section id="watch"')[0]||'';
assert.ok(studio,'GO LIVE studio must remain');
assert.ok(!studio.includes('AKSES AWAL')&&!studio.includes('PUBLIC / GRATIS'),'No redundant pricing/access tutorial in GO LIVE');
assert.ok(!studio.includes('Semua siaran dimulai publik'),'Remove self-explanatory prose');
assert.ok(studio.includes('id="createRoom"'),'Transmit control must remain unchanged');
assert.ok(html.includes("personLink.onclick=()=>openCreatorProfile(person.handle)"),'Followers and Following identities open ME');
assert.ok(html.includes("personLink.append(label);row.append(personLink,makeFollowButton(person.handle))"),'Profile and follow actions are separate');
assert.ok(html.includes("name.onclick=event=>{event.stopPropagation();openCreatorProfile(item.handle)}"),'Message names open ME');
assert.ok(html.includes("person.onclick=event=>{event.stopPropagation();openCreatorProfile(item.handle)}"),'Message avatars open ME');
assert.ok(html.includes("person.onclick=()=>openCreatorProfile(req.handle)"),'Message requests can open profile');
assert.ok(html.includes("if(origin==='messagesPage'&&returnChat)openMessages(returnChat)"),'Returning from chat profile preserves chat navigation');
assert.ok(html.includes("publicProfileOrigin=['socialConnectionsPage','messagesPage'].includes(origin)?origin:'socialPage'"),'Profile back origin is retained');

// Card author identity: only a compact avatar is interactive, name remains plain text.
assert.ok(html.includes("const avatarButton=document.createElement('button');avatarButton.type='button';avatarButton.className='social-avatar-open'"));
assert.ok(html.includes("avatarButton.onclick=()=>openCreatorProfile(entry.handle)"));
assert.ok(html.includes("const author=document.createElement('span');author.className='social-display-name'"));
assert.ok(!html.includes("const author=document.createElement('button');author.type='button';author.className='profile-open'"));
assert.ok(html.includes('.profile-post-card .post-top .social-avatar-open{display:grid;grid-template-areas:"avatar";place-items:center;width:40px;height:40px;'));
assert.ok(html.includes('.profile-post-card .post-top .social-avatar-fallback[hidden],'));
assert.ok(html.includes('.profile-post-card .post-top .social-avatar-open img[hidden]{display:none!important}'));
assert.ok(html.includes('.message-chat-avatar{display:grid;grid-template-areas:"avatar";place-items:center;width:48px;height:48px;'));
assert.ok(html.includes('.message-chat-avatar .message-avatar-fallback[hidden],'));
assert.ok(html.includes('.message-chat-avatar img[hidden]{display:none!important}'));
assert.ok(html.includes("avatar.onload=()=>{fallback.hidden=true;avatar.hidden=false}"));
assert.ok(html.includes("img.onload=()=>{fallback.hidden=true;img.hidden=false}"));
console.log('PASS navigation signature, compact avatar navigation, plain names and repost actions');
